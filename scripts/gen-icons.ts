/**
 * Generates every app icon from the design tokens (app/tokens.css →
 * lib/design-tokens.generated.ts), so the favicon / PWA icons can never drift
 * from the palette:
 *   app/icon.svg                         favicon (vector)
 *   public/icons/icon-{72..512}.png      manifest "any" icons (rounded tile)
 *   public/icons/maskable-{192,512}.png  manifest "maskable" (full-bleed, 80% safe zone)
 *   public/apple-touch-icon.png          180×180, full-bleed (iOS rounds it; default iOS path)
 *   app/apple-icon.png                   same art → Next emits <link rel="apple-touch-icon">
 *   public/icon-192.png, icon-512.png    legacy paths (extension/README) — same art
 *   public/icons/shortcut-*.png          96×96 manifest shortcut icons
 *
 *   npm run icons      (needs the pre-installed Playwright Chromium)
 */
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { DESIGN_TOKENS } from "../lib/design-tokens.generated";

const T = DESIGN_TOKENS.light;
const root = resolve(__dirname, "..");

const GLYPH = `
  <path d="M12 17V14.5C12 13.12 13.12 12 14.5 12H17M27 12H29.5C30.88 12 32 13.12 32 14.5V17M32 27V29.5C32 30.88 30.88 32 29.5 32H27M17 32H14.5C13.12 32 12 30.88 12 29.5V27" stroke="${T.white}" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"/>
  <path d="M22 16.5V26M22 26L18 22M22 26L26 22" stroke="${T.white}" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"/>`;

const SHORTCUT_GLYPHS: Record<string, string> = {
  // download arrow inside a story-ring (no Instagram camera glyph — PRD §3.1 / K22)
  instagram: `<circle cx="22" cy="22" r="11" stroke="${T.white}" stroke-width="2.2"/><path d="M22 16.5V26M22 26L18 22M22 26L26 22" stroke="${T.white}" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"/>`,
  tools: `<rect x="12" y="12" width="8" height="8" rx="2" stroke="${T.white}" stroke-width="2.2"/><rect x="24" y="12" width="8" height="8" rx="2" stroke="${T.white}" stroke-width="2.2"/><rect x="12" y="24" width="8" height="8" rx="2" stroke="${T.white}" stroke-width="2.2"/><rect x="24" y="24" width="8" height="8" rx="2" stroke="${T.white}" stroke-width="2.2"/>`,
  history: `<circle cx="22" cy="22" r="10" stroke="${T.white}" stroke-width="2.2"/><path d="M22 16v6l4 3" stroke="${T.white}" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"/>`,
};

/** @param fullBleed  square background (maskable / apple) instead of a rounded tile */
function svg(opts: { fullBleed?: boolean; scale?: number; glyph?: string } = {}): string {
  const { fullBleed = false, scale = 1, glyph = GLYPH } = opts;
  const inner = scale === 1 ? glyph : `<g transform="translate(${22 - 22 * scale} ${22 - 22 * scale}) scale(${scale})">${glyph}</g>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="44" height="44" viewBox="0 0 44 44" fill="none">
  <!-- AUTO-GENERATED by scripts/gen-icons.ts from app/tokens.css — do not edit -->
  <defs><linearGradient id="g" x1="0" y1="44" x2="44" y2="0" gradientUnits="userSpaceOnUse"><stop stop-color="${T["cta-start"]}"/><stop offset="1" stop-color="${T["cta-end"]}"/></linearGradient></defs>
  <rect width="44" height="44" rx="${fullBleed ? 0 : 11}" fill="url(#g)"/>${inner}
</svg>`;
}

async function main() {
  writeFileSync(resolve(root, "app/icon.svg"), svg() + "\n");
  mkdirSync(resolve(root, "public/icons"), { recursive: true });
  const require = createRequire(__filename);
  // Pre-installed global Playwright (not a project dependency) — minimal local typing.
  type Page = {
    setViewportSize(s: { width: number; height: number }): Promise<void>;
    setContent(html: string): Promise<void>;
    screenshot(o: { path: string; omitBackground: boolean; clip: { x: number; y: number; width: number; height: number } }): Promise<unknown>;
  };
  type Browser = { newPage(o: { deviceScaleFactor: number }): Promise<Page>; close(): Promise<void> };
  const { chromium } = require("playwright") as { chromium: { launch(): Promise<Browser> } };
  const browser = await chromium.launch();
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  async function png(markup: string, px: number, out: string) {
    await page.setViewportSize({ width: px, height: px });
    await page.setContent(`<html><body style="margin:0;background:transparent">${markup.replace("<svg ", `<svg style="display:block;width:${px}px;height:${px}px" `)}</body></html>`);
    await page.screenshot({ path: resolve(root, out), omitBackground: true, clip: { x: 0, y: 0, width: px, height: px } });
    console.log("wrote", out);
  }
  for (const px of [72, 96, 128, 144, 152, 192, 384, 512]) await png(svg(), px, `public/icons/icon-${px}.png`);
  for (const px of [192, 512]) await png(svg({ fullBleed: true, scale: 0.8 }), px, `public/icons/maskable-${px}.png`);
  await png(svg({ fullBleed: true, scale: 0.86 }), 180, "public/apple-touch-icon.png");
  await png(svg({ fullBleed: true, scale: 0.86 }), 180, "app/apple-icon.png"); // Next file convention → <link rel="apple-touch-icon">
  await png(svg(), 192, "public/icon-192.png");
  await png(svg(), 512, "public/icon-512.png");
  for (const [name, glyph] of Object.entries(SHORTCUT_GLYPHS)) await png(svg({ glyph }), 96, `public/icons/shortcut-${name}.png`);
  await browser.close();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
