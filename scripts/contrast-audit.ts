/**
 * Runs `python3 scripts/contrast_check.py "<fg>" "<bg>"` for EVERY audited
 * text/background pair in BOTH themes (pairs come from lib/contrast-pairs.ts,
 * translucent tokens already composited onto their worst-case backdrop) and
 * writes docs/design/contrast-report.md. Exit code 1 on any failure.
 *
 *   npm run contrast
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { allPairs } from "../lib/contrast-pairs";

const root = resolve(__dirname, "..");
const css = readFileSync(resolve(root, "app/tokens.css"), "utf8");
const pairs = allPairs(css);
const rows: string[] = [];
let failures = 0;
for (const p of pairs) {
  const out = execFileSync("python3", [resolve(root, "scripts/contrast_check.py"), p.fgHex, p.bgHex], { encoding: "utf8" }).trim();
  const m = out.match(/: ([\d.]+):1/);
  const ratio = m ? Number(m[1]) : NaN;
  const pass = ratio >= p.min;
  if (!pass) failures++;
  rows.push(`| ${p.theme} | \`${p.fg}\` | \`${p.bg}\` | ${p.fgHex} / ${p.bgHex} | ${ratio.toFixed(2)}:1 | ${p.kind} ≥ ${p.min} | ${pass ? "PASS" : "**FAIL**"} | ${p.use} |`);
}
const md = `# Contrast report — app/tokens.css

Generated by \`npm run contrast\` (\`scripts/contrast-audit.ts\`), which runs
\`python3 scripts/contrast_check.py "<fg>" "<bg>"\` (ui-design-master toolkit) for
every pair below. Translucent tokens (glass, tinted fills) are composited onto
their worst-case backdrop first; gradients are sampled at 101 points and the
worst point is reported. Thresholds: text ≥ 4.5:1, large text / UI ≥ 3:1.

**${pairs.length} pairs · ${pairs.length - failures} pass · ${failures} fail**

| Theme | Foreground | Background | Hex (fg / bg) | Ratio | Rule | Result | Used for |
|---|---|---|---|---|---|---|---|
${rows.join("\n")}

Decorative-only (never behind text, not audited as text): \`--ig-yellow\` (white 1.35:1)
and \`--ig-orange\` (white 2.60:1) appear only in the logo / Story-Ring / aurora.
`;
mkdirSync(resolve(root, "docs/design"), { recursive: true });
writeFileSync(resolve(root, "docs/design/contrast-report.md"), md);
console.log(`${pairs.length} pairs, ${failures} failing → docs/design/contrast-report.md`);
process.exit(failures ? 1 : 0);
