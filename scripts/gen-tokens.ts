/**
 * Generates lib/design-tokens.generated.ts from app/tokens.css so that code
 * which cannot read CSS variables at runtime (OG image, manifest, viewport
 * theme-color, icon rasteriser) still gets its colours from the single source
 * of truth. `npm test` (lib/tokens.test.ts) fails if the file is stale.
 *
 *   npm run tokens
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { collectTokens, resolveTokens } from "../lib/tokens-parse";

/** Tokens exported to TS (keep small — only what non-CSS consumers need). */
export const EXPORTED = [
  "--bg-base", "--bg-surface", "--text-primary", "--text-secondary", "--text-brand", "--text-on-primary",
  "--color-primary", "--cta-start", "--cta-mid", "--cta-end", "--accent", "--border-default",
  "--ig-yellow", "--ig-orange", "--ig-pink", "--ig-purple", "--ig-blue", "--white", "--black",
] as const;

export function buildModule(css: string): string {
  const pick = (theme: "light" | "dark") => {
    const all = resolveTokens(collectTokens(css, theme));
    const out: Record<string, string> = {};
    for (const k of EXPORTED) out[k.slice(2)] = all[k] ?? "";
    return out;
  };
  const data = { light: pick("light"), dark: pick("dark") };
  return `/* AUTO-GENERATED by scripts/gen-tokens.ts from app/tokens.css — do not edit. Run \`npm run tokens\`. */
export const DESIGN_TOKENS = ${JSON.stringify(data, null, 2)} as const;
export type TokenName = keyof typeof DESIGN_TOKENS.light;
`;
}

if (process.argv[1] && process.argv[1].endsWith("gen-tokens.ts")) {
  const root = resolve(__dirname, "..");
  const css = readFileSync(resolve(root, "app/tokens.css"), "utf8");
  writeFileSync(resolve(root, "lib/design-tokens.generated.ts"), buildModule(css));
  console.log("wrote lib/design-tokens.generated.ts");
}
